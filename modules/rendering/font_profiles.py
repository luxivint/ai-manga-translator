UPPER_STYLES = {"shout", "sfx", "sign", "title"}
CAPS_FALLBACK = "assets/Comic Geek.ttf"


@lru_cache(maxsize=1)
def traits_table() -> dict[str, dict]:
    if TRAITS_FILE.exists():
        return json.loads(TRAITS_FILE.read_text(encoding="utf-8"))
    return {}


def traits_of(rel: str) -> dict | None:
    t = traits_table().get(rel)
    if t is not None:
        return t
    p = ROOT / rel
    if p.exists():
        try:
            return {**fm.font_traits(p), **fm.glyph_coverage(p)}
        except Exception:
            return None
    return None


def is_usable(rel: str) -> bool:
    if rel in BLOCKLIST:
        return False
    t = traits_of(rel)
    return bool(t) and bool(t.get("turkish_ok", False))


def caps_only(rel: str) -> bool:
    """True when the font has no real lowercase (must be fed upper-case Turkish text)."""
    t = traits_of(rel)
    return bool(t and t.get("caps"))


def casing_for(rel: str, style: str, policy: str = "upper") -> str:
    """'upper' or 'natural'. Default policy 'upper' (product decision: everything in capitals);
    policy 'auto' keeps natural case except for caps-only fonts and UPPER_STYLES."""
    if policy == "upper":
        return "upper"
    if caps_only(rel) or (style or "").lower() in UPPER_STYLES:
        return "upper"
    return "natural"


_PUNCT_SUBS = {"…": "...", "“": '"', "”": '"', "‘": "'", "’": "'", "–": "-", "—": "-", "«": '"', "»": '"'}


def sanitize_for_font(text: str, rel: str) -> str:
    """Replace punctuation the font lacks (they would show as boxes or fall back to another font)."""
    miss = (traits_of(rel) or {}).get("missing_punct", [])
    out = text
    for ch in miss:
        if ch in _PUNCT_SUBS:
            out = out.replace(ch, _PUNCT_SUBS[ch])
    return out


def ranked_candidates(style: str) -> list[str]:
    style = (style or "normal").lower()
    ranks = STYLE_RANKS.get(style) or STYLE_RANKS["normal"]
    return [rel for rel in ranks if is_usable(rel)]


def match_font(style: str, src: dict | None, max_candidates: int = 4, rank_penalty: float = 0.06) -> str:
    """Closest-looking usable candidate for source lettering traits `src` (see font_metrics.source_traits).

    Heuristic: distance over stem weight (x4), slant (x3), character aspect (x1.2) plus a small
    penalty per rank so the curated order wins ties. Strongly italic sources (slant>0.18) also
    consider the first slanted font from the shout/sfx lists. Returns a path relative to the repo root.
    """
    cands = ranked_candidates(style)
    if not cands:
        return CAPS_FALLBACK
    if not src or src.get("height", 0) < 8:
        return cands[0]
    pool = cands[:max_candidates]
    # heavy slanted display fonts are only for SHOUTS; slanted ordinary speech keeps an upright font of the
    # right weight and gets a synthetic oblique (see wants_synthetic_italic)
    if abs(src.get("slant", 0.0)) > 0.18 and (style or "normal").lower() == "shout":
        for rel in ranked_candidates("shout") + ranked_candidates("sfx"):
            if rel not in pool and (traits_of(rel) or {}).get("slant", 0) > 0.15:
                pool.append(rel)
                break
    best, best_d = pool[0], 1e9
    for rank, rel in enumerate(pool):
        d = fm.trait_distance(src, traits_of(rel)) + rank_penalty * rank
        if d < best_d:
            best, best_d = rel, d
    return best


SYNTHETIC_ITALIC_STYLES = {"normal", "thought", "narration", "whisper", "handwriting", "sign", "phone"}
SYNTHETIC_ITALIC_MIN_SLANT = 0.12  # tan(angle) ~ 7 degrees; Qt's synthetic oblique is ~ 8-12 degrees


def wants_synthetic_italic(style: str, src: dict | None, rel: str | None = None) -> bool:
    """True when the source lettering leans (tan > 0.12) but the chosen font is upright and the style is not a
    shout/SFX (those pick a genuinely slanted display font): the renderer then sets the font italic, which Qt
    synthesises as a light oblique so the stroke weight stays that of the matched font."""
    if not src or src.get("height", 0) < 8 or (style or "normal").lower() not in SYNTHETIC_ITALIC_STYLES:
        return False
    if src.get("slant", 0.0) < SYNTHETIC_ITALIC_MIN_SLANT:
        return False
    return abs((traits_of(rel) or {}).get("slant", 0.0)) < 0.1 if rel else True
