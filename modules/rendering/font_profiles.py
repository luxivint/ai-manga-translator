UPPER_STYLES = {"shout", "sfx", "sign", "title"}
CAPS_FALLBACK = "assets/Comic Geek.ttf"


@lru_cache(maxsize=1)
def traits_table() -> dict[str, dict]:
    if TRAITS_FILE.exists():
        return json.loads(TRAITS_FILE.read_text(encoding="utf-8"))
    return {}


def traits_of(rel: str) -> dict | None:
    t = traits_table().get(rel)
    if t is not None:
        return t
    p = ROOT / rel
    if p.exists():
        try:
            return {**fm.font_traits(p), **fm.glyph_coverage(p)}
        except Exception:
            return None
    return None


def is_usable(rel: str) -> bool:
    if rel in BLOCKLIST:
        return False
    t = traits_of(rel)
    return bool(t) and bool(t.get("turkish_ok", False))


def caps_only(rel: str) -> bool:
    """True when the font has no real lowercase (must be fed upper-case Turkish text)."""
    t = traits_of(rel)
    return bool(t and t.get("caps"))


def casing_for(rel: str, style: str, policy: str = "upper") -> str:
    """'upper' or 'natural'. Default policy 'upper' (product decision: everything in capitals);
    policy 'auto' keeps natural case except for caps-only fonts and UPPER_STYLES."""
    if policy == "upper":
        return "upper"
    if caps_only(rel) or (style or "").lower() in UPPER_STYLES:
        return "upper"
    return "natural"


_PUNCT_SUBS = {"…": "...", "“": '"', "”": '"', "‘": "'", "’": "'", "–": "-", "—": "-", "«": '"', "»": '"'}


def sanitize_for_font(text: str, rel: str) -> str:
    """Replace punctuation the font lacks (they would show as boxes or fall back to another font)."""
    miss = (traits_of(rel) or {}).get("missing_punct", [])
    out = text
    for ch in miss:
        if ch in _PUNCT_SUBS:
            out = out.replace(ch, _PUNCT_SUBS[ch])
    return out


# --- normal speech: heavy preference for the 'konuşma' (speech) font folder -----------------------------
SPEECH_FOLDER = K + "konuşma/"
# Measured stem/cap-height of the folder: CCVictorySpeech 0.103, CatBang 0.122, mercyorj 0.135 (all readable
# in white balloons at small sizes); Chinacat 0.085 / hairline scripts are the "thin" look users complain about.
# Anything below 0.10 is rejected from the speech pool. Override: env FONT_SPEECH_MIN_STEM.
SPEECH_MIN_STEM = 0.10
# Neighbouring bubbles must share one family: the anchor (first pool font) wins unless another pool font
# is closer to the source lettering by more than this trait-distance margin (wide/condensed/very different weight).
SPEECH_SWITCH_MARGIN = 0.30


def _min_stem() -> float:
    try:
        return float(os.environ.get("FONT_SPEECH_MIN_STEM", SPEECH_MIN_STEM))
    except ValueError:
        return SPEECH_MIN_STEM


def _file_exists(rel: str) -> bool:
    return (ROOT / rel).is_file()


def _user_style_map() -> dict[str, list[str]]:
    """Optional JSON override (env FONT_MAP_FILE): {"normal": ["FONT KLASÖR/x/Font.otf" | "folder", ...]}.
    An entry that is a folder name expands to its fonts; a user-supplied style replaces the built-in ranks
    (and, for 'normal', disables the speech-pool preference)."""
    path = os.environ.get("FONT_MAP_FILE", "").strip()
    if not path or not Path(path).is_file():
        return {}
    try:
        raw = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    out: dict[str, list[str]] = {}
    for style, entries in (raw.items() if isinstance(raw, dict) else []):
        entries = [entries] if isinstance(entries, str) else list(entries)
        expanded: list[str] = []
        for e in entries:
            if isinstance(e, str) and "/" not in e and "\\" not in e:  # bare folder name
                expanded += sorted(r for r in traits_table() if r.startswith(K + e.strip("/") + "/"))
            elif isinstance(e, str):
                expanded.append(e.replace("\\", "/"))
        out[str(style).lower()] = expanded
    return out


def speech_pool() -> list[str]:
    """Fonts of the konuşma folder that exist, cover Turkish and are not thin. Curated order first
    (STYLE_RANKS['normal'] konuşma entries), then any other folder font heaviest-first."""
    min_stem = _min_stem()
    found = {r for r in traits_table() if r.startswith(SPEECH_FOLDER)}
    d = ROOT / "FONT KLASÖR" / "konuşma"
    if d.is_dir():
        found |= {SPEECH_FOLDER + p.name for p in d.iterdir() if p.suffix.lower() in (".ttf", ".otf")}
    ok = [r for r in found if _file_exists(r) and is_usable(r) and (traits_of(r) or {}).get("stem", 0.0) >= min_stem]
    curated = [r for r in STYLE_RANKS["normal"] if r in ok]
    rest = sorted((r for r in ok if r not in curated), key=lambda r: (-(traits_of(r) or {}).get("stem", 0.0), r))
    return curated + rest


def thought_uses_speech_pool() -> bool:
    """Thought balloons are set in the speech font (FONT_THOUGHT_SPEECH_POOL, default true): the thin Chinacat family
    read as a different, light typeface next to the speech balloons of the same character; a slanted source still gets
    the synthetic oblique."""
    return os.environ.get("FONT_THOUGHT_SPEECH_POOL", "true").lower() == "true"


def ranked_candidates(style: str) -> list[str]:
    style = (style or "normal").lower()
    user = _user_style_map().get(style)
    if user is not None:
        return [rel for rel in user if is_usable(rel)]
    if style == "normal" or (style == "thought" and thought_uses_speech_pool()):
        pool = speech_pool()
        if pool:
            return pool
    ranks = STYLE_RANKS.get(style) or STYLE_RANKS["normal"]
    return [rel for rel in ranks if is_usable(rel)]


def match_font(style: str, src: dict | None, max_candidates: int = 4, rank_penalty: float = 0.06) -> str:
    """Closest-looking usable candidate for source lettering traits `src` (see font_metrics.source_traits).

    Heuristic: distance over stem weight (x4), slant (x3), character aspect (x1.2) plus a small
    penalty per rank so the curated order wins ties. Strongly italic sources (slant>0.18) also
    consider the first slanted font from the shout/sfx lists. 
    Normal speech ranks only inside the speech pool and sticks to the anchor (first) font unless another
    pool font is closer by SPEECH_SWITCH_MARGIN, so a page/series looks consistent.
    """
    cands = ranked_candidates(style)
    if not cands:
        return CAPS_FALLBACK
    if not src or src.get("height", 0) < 8:
        return cands[0]
    pool = cands[:max_candidates]
    # heavy slanted display fonts are only for SHOUTS; slanted ordinary speech keeps an upright font of the
    # right weight and gets a synthetic oblique (see wants_synthetic_italic)
    if abs(src.get("slant", 0.0)) > 0.18 and (style or "normal").lower() == "shout":
        # only the shout list: the slanted SFX script fonts (DREAMER_ADDICT...) are unreadable in a balloon
        for rel in ranked_candidates("shout"):
            if rel not in pool and (traits_of(rel) or {}).get("slant", 0) > 0.15:
                pool.append(rel)
                break
    in_speech_pool = (style or "normal").lower() in ("normal", "thought") and cands[0].startswith(SPEECH_FOLDER)
    if in_speech_pool:
        # the pool is already curated for readability: pure trait distance, anchor wins unless clearly worse
        dists = {rel: fm.trait_distance(src, traits_of(rel)) for rel in pool}
        best = min(pool, key=lambda r: dists[r])
        return best if dists[pool[0]] - dists[best] > SPEECH_SWITCH_MARGIN else pool[0]
    best, best_d = pool[0], 1e9
    for rank, rel in enumerate(pool):
        d = fm.trait_distance(src, traits_of(rel)) + rank_penalty * rank
        if d < best_d:
            best, best_d = rel, d
    return best


SYNTHETIC_ITALIC_STYLES = {"normal", "thought", "narration", "whisper", "handwriting", "sign", "phone"}
# tan(angle) ~ 10 degrees. Upright comic lettering measures 0.04-0.16 (the estimator has a per-series bias, e.g. ~0.10
# on one series), real italic 0.30-0.48: 0.12 turned upright balloons italic. Override: FONT_ITALIC_MIN_SLANT.
SYNTHETIC_ITALIC_MIN_SLANT = 0.17


def _italic_min_slant() -> float:
    try:
        return float(os.environ.get("FONT_ITALIC_MIN_SLANT", SYNTHETIC_ITALIC_MIN_SLANT))
    except ValueError:
        return SYNTHETIC_ITALIC_MIN_SLANT


def wants_synthetic_italic(style: str, src: dict | None, rel: str | None = None) -> bool:
    """True when the source lettering leans (tan > FONT_ITALIC_MIN_SLANT) but the chosen font is upright and the style
    is not a shout/SFX (those pick a genuinely slanted display font): the renderer then sets the font italic, which Qt
    synthesises as a light oblique so the stroke weight stays that of the matched font."""
    if not src or src.get("height", 0) < 8 or (style or "normal").lower() not in SYNTHETIC_ITALIC_STYLES:
        return False
    if src.get("slant", 0.0) < _italic_min_slant():
        return False
    return abs((traits_of(rel) or {}).get("slant", 0.0)) < 0.1 if rel else True
